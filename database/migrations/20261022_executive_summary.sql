-- Branch-admin Executive Summary configuration and delivery history.
-- Report data is calculated from the existing business tables at run time.

CREATE TABLE IF NOT EXISTS `executive_summary_configs` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `config_id` VARCHAR(64) NOT NULL,
  `branch_id` VARCHAR(50) NOT NULL,
  `enabled` TINYINT(1) NOT NULL DEFAULT 0,
  `schedule_type` ENUM('weekly','monthly') NOT NULL DEFAULT 'weekly',
  `send_hour` TINYINT UNSIGNED NOT NULL DEFAULT 9,
  `send_minute` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `timezone` VARCHAR(64) NOT NULL DEFAULT 'Asia/Kolkata',
  `week_starts_on` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `inactivity_days` SMALLINT UNSIGNED NOT NULL DEFAULT 30,
  `recipient_emails_json` LONGTEXT NOT NULL,
  `sections_json` LONGTEXT NOT NULL,
  `last_successful_period_key` VARCHAR(64) DEFAULT NULL,
  `last_attempt_at` DATETIME DEFAULT NULL,
  `last_success_at` DATETIME DEFAULT NULL,
  `last_error` TEXT DEFAULT NULL,
  `create_by` VARCHAR(100) DEFAULT NULL,
  `modify_by` VARCHAR(100) DEFAULT NULL,
  `create_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `modify_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_executive_summary_config_id` (`config_id`),
  UNIQUE KEY `uq_executive_summary_branch` (`branch_id`),
  KEY `idx_executive_summary_enabled` (`enabled`, `schedule_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `executive_summary_runs` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `run_id` VARCHAR(64) NOT NULL,
  `config_id` VARCHAR(64) NOT NULL,
  `branch_id` VARCHAR(50) NOT NULL,
  `period_start` DATE NOT NULL,
  `period_end` DATE NOT NULL,
  `inactivity_cutoff_date` DATE NOT NULL,
  `period_key` VARCHAR(64) NOT NULL,
  `idempotency_key` VARCHAR(160) NOT NULL,
  `trigger_type` ENUM('scheduled','manual','preview') NOT NULL,
  `status` ENUM('queued','generating','sent','downloaded','failed') NOT NULL DEFAULT 'queued',
  `recipient_emails_json` LONGTEXT NOT NULL,
  `sections_json` LONGTEXT NOT NULL,
  `effective_config_json` LONGTEXT NOT NULL,
  `pdf_filename` VARCHAR(255) DEFAULT NULL,
  `pdf_size_bytes` BIGINT UNSIGNED DEFAULT NULL,
  `message_id` VARCHAR(500) DEFAULT NULL,
  `attempt_count` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `error_message` TEXT DEFAULT NULL,
  `started_at` DATETIME DEFAULT NULL,
  `finished_at` DATETIME DEFAULT NULL,
  `create_by` VARCHAR(100) DEFAULT NULL,
  `create_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_executive_summary_run_id` (`run_id`),
  UNIQUE KEY `uq_executive_summary_idempotency` (`idempotency_key`),
  KEY `idx_executive_summary_runs_branch_period` (`branch_id`, `period_end`, `status`),
  KEY `idx_executive_summary_runs_config` (`config_id`, `create_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
